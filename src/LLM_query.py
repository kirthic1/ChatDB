# Defining the system role for the LLM model to generate formal SQL queries
role = {
    "role": "system",
    "content": """
You are an AI that creates a single, formal, and accurate SQL query in correct syntax to answer the user's prompt. 
You MUST handle SELECT, INSERT, DELETE, UPDATE commands, and any other SQl commands as well. 
You MUST also be able to give information schema of the database and of each table in the database.
Watch very carefully for synonyms:
'add', 'create, 'new entry' --> INSERT
'remove', 'delete', 'erase' --> DELETE
'change', 'update', 'modify' --> UPDATE
Along with the user's prompt, you are provided the schema of the database that the user is referring to. 
The database schema is in the form of a python dictionary where the keys are the table names, and the values are the columns of the table.
Additionally, along with the user's prompt, you are provided the exact table names in a python list that the user is referring to.
The user's prompt may mention a column name, but you need to infer the actual column name from the schema provided.
For example, if the user mentions the column name "victim age", you need to infer from the schema that the actual column name is "vict_age". 
If any table names, column names, or database names contain spaces, surround them with backticks (`) to match MySQL syntax.
The user may indicate interest in a specific table, but you are allowed to use any relevant tables to form the correct query. 
If a join is required to answer the question properly, include it.
If the query involves multiple tables or joins, qualify column names using the full table name or table alias (e.g., victims.victim_age or v.victim_age). This prevents ambiguous column errors in MySQL, especially for shared column names like 'id' or 'weapon_id'. 
If the user wants the row(s) for the group with the lowest or highest average, don’t compare individual values to the average — instead, find the right group first with a subquery, then filter the full data using that group.
Use aliases when appropriate and be consistent in SELECT, JOIN, WHERE, GROUP BY, and ORDER BY clauses.
DO NOT use LIMIT inside an IN/ALL/ANY/SOME subquery, as this is not supported in MySQL. Use JOINs with derived tables (aliased subqueries) to apply LIMIT instead.
If the user’s query contains a keyword that may only partially match a database value (e.g., 'knife' vs 'kitchen knife'), use LIKE '%...%' instead of = in the WHERE clause to improve matching.
You will return only the SQL query, and no explanation necessary. 
Do not include markdown formatting like prefix, sql
"""
        }


def execute_query(query: str, choice: str) -> List[Tuple]:
    """
    Defines function to execute SQL query generated by the nlp model
    :param query: SQl query generated by nlp model
    :param choice: user's choice of database
    :return: result of sql query in the form of list of tuples where each tuple is a row
    """
    # Connecting to SQL database of user's choice
    conn = get_connection(choice)

    # With the connection object, creating a cursor object which will allow communication with the database
    cursor = conn.cursor()

    # With the cursor object, executing the SQL query
    cursor.execute(query)

    # Fetches all rows returned by the query as a list of tuples where each tuple is a row
    results = cursor.fetchall()

    # For INSERT, DELETE, UPDATE transactions in order to save changes permanently
    conn.commit()
    cursor.close()
    conn.close()
    return results

def tablechoice(database_choice: str) -> List[pd.DataFrame]:
    """
    Defines function that uses the llm model to understand the table names the user would like to focus on
    :param database_choice: user's choice of database
    :return: list of table names that user would like to focus on
    """
    api_key = os.getenv("LLM_API_KEY")
    role = {
        "role": "system",
        "content": """
You are an AI that identfies the correct table names that the user is referring to based on the database schema and 
user prompt provided. The user prompt will have table names either in natural language, or separated by space or some 
punctuation or not separated by anything. You need to decipher the table names from the user prompt. 
You will return the correct table names in the form of a python list, and no explanation necessary. (e.g., ['weapons', 'crime_incidents']) 
Do not include any type of formatting. 
The table names should be accurate and be exactly formatted as in the database schema except without any quotes or punctuation. 
Always return the result in the form of a python list. Example: ['immunization', 'life_expectancy', 'maternal_health'] """
}

    messages = [role]

    tables = []
    while True:
        table_choice = input("""👉 Which tables from the database you chose would you like to query? Even if you enter certain table names here, it does not limit you in asking about other tables. You may still ask about other tables. You may enter many table names separated by a space or any punctuation: """)

        messages.append({"role": "user", "content": f"""user table choice:
{table_choice}

database schema:
{get_schema(database_choice)}
"""})

        client = OpenAI(api_key=api_key)
        response = client.chat.completions.create(messages=messages, model="gpt-4o-mini")
        total_tokens_tracker.add_tokens(response.usage.total_tokens)

        result = response.choices[0].message.content.strip()

        tables_temp_list = ast.literal_eval(result)

        if isinstance(tables_temp_list, list):
            tables.extend(tables_temp_list)


        question = input("""👉 Would you like to choose another table in addition to what you already chose? Enter either the letter y for yes or n for no: """)

        if question.lower() == "y" or question.lower() == "yes":
            continue
        else:
            break
    return tables



